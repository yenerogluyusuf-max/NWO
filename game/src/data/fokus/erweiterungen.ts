import type { FokusAst, FokusBedingung, FokusDefinition, FokusWirkung } from "./typen";

/** Kompakter Baukasten, damit 44 Foki lesbar bleiben. Defaults: tage 90, kapital 10, aufmerksamkeit 1. */
function fok(v: {
  id: string;
  ast: FokusAst;
  t: string;
  tTr: string;
  tEn: string;
  u: string;
  uTr: string;
  uEn: string;
  b: string;
  bTr: string;
  bEn: string;
  voraus?: string[];
  ausschluesse?: string[];
  tage?: number;
  kapital?: number;
  bedingungen?: FokusBedingung[];
  wirkung: FokusWirkung;
  zitat?: { text: string; urheber: string };
  spalte: number;
  zeile: number;
}): FokusDefinition {
  return {
    id: v.id,
    ast: v.ast,
    titel: v.t,
    titelTr: v.tTr,
    titelEn: v.tEn,
    untertitel: v.u,
    untertitelTr: v.uTr,
    untertitelEn: v.uEn,
    beschreibung: v.b,
    beschreibungTr: v.bTr,
    beschreibungEn: v.bEn,
    voraus: v.voraus ?? [],
    ausschluesse: v.ausschluesse,
    tage: v.tage ?? 90,
    kapital: v.kapital ?? 10,
    aufmerksamkeit: 1,
    bedingungen: v.bedingungen,
    wirkung: v.wirkung,
    zitat: v.zitat,
    raster: { spalte: v.spalte, zeile: v.zeile },
  };
}

